    function translateOne(text) {
        if (Object.prototype.hasOwnProperty.call(EXACT, text)) return EXACT[text];
        for (var i = 0; i < PATTERNS.length; i += 1) {
            if (PATTERNS[i][0].test(text)) return text.replace(PATTERNS[i][0], PATTERNS[i][1]);
        }
        return null;
    }

    // Returns the Urdu for an English UI string, or null when there is none.
    // Hints joined with " · " are translated part by part.
    function translate(value) {
        var text = String(value === undefined || value === null ? '' : value).replace(/\s+/g, ' ').trim();
        if (!text || !/[A-Za-z]/.test(text)) return null;
        var whole = translateOne(text);
        if (whole !== null) return whole;
        if (text.indexOf(' · ') < 0) return null;
        var changed = false;
        var parts = text.split(' · ').map(function (part) { var urdu = translateOne(part); if (urdu !== null) changed = true; return urdu === null ? part : urdu; });
        return changed ? parts.join(' · ') : null;
    }

